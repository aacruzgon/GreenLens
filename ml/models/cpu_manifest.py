"""Write manifest.cpu.toml: manifest.toml with every fp16 ONNX file swapped for its fp32 export.

    python -m ml.models.cpu_manifest

For running the perception code on a laptop with ORT_EP=cpu (docs/vision/dev-roadmap.md,
task M9): ONNX Runtime's CPU execution provider runs fp32 graphs, not the fp16 ones the GPU
workers load. Each fp32 file comes from the same export as its fp16 file, with the same inputs,
outputs and recipe. The heads were fitted on the fp16 BioCLIP features, so CPU numbers differ
from the rig's in the third decimal; use it for development, never for evaluation.

Standard library only. Rerun it whenever manifest.toml changes, and commit both files.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "manifest.toml"
TARGET = HERE / "manifest.cpu.toml"
FILES = HERE / "files"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    lines = SOURCE.read_text().splitlines()
    out = [
        "# GENERATED by `python -m ml.models.cpu_manifest` from manifest.toml: don't edit.",
        "# The fp32 exports, for ORT_EP=cpu on a development machine (docs/vision/dev-roadmap.md).",
        "#",
    ]
    swapped = 0
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r'^(file\s*=\s*")(.+)-fp16\.onnx(".*)$', line)
        if m:
            fp32 = f"{m[2]}-fp32.onnx"
            path = FILES / fp32
            if not path.exists():
                raise SystemExit(f"{path} is missing: export it, or fetch it with python -m ml.models.fetch --cpu")
            out.append(f"{m[1]}{fp32}{m[3]}")
            nxt = lines[i + 1]
            if not nxt.startswith("sha256"):
                raise SystemExit(f"expected sha256 after {line!r}")
            out.append(re.sub(r'"[0-9a-f]{64}"', f'"{sha256(path)}"', nxt))
            swapped += 1
            i += 2
            continue
        if re.match(r'^precision\s*=\s*"fp16"', line):
            out.append(re.sub(r'"fp16".*$', '"fp32"', line))
        else:
            out.append(line)
        i += 1
    TARGET.write_text("\n".join(out) + "\n")
    print(f"{TARGET.name}: {swapped} files swapped to fp32")


if __name__ == "__main__":
    main()
