"""Write manifest.cpu.toml: manifest.toml with every fp16 ONNX file swapped for its fp32 export,
and every head file swapped for a twin that names the fp32 BioCLIP export.

    python -m ml.models.cpu_manifest

For running the perception code on a laptop with ORT_EP=cpu (docs/vision/dev-roadmap.md,
task M9): ONNX Runtime's CPU execution provider runs fp32 graphs, not the fp16 ones the GPU
workers load. Each fp32 file comes from the same export as its fp16 file, with the same inputs,
outputs and recipe.

A head's `features` names the exact BioCLIP file it was fitted on (ml/models/FORMATS.md), and
the worker refuses a head whose `features` differ from the manifest's `bioclip` file. The heads
were fitted on the fp16 features, so each head gets a twin, `<stem>.cpu.json`, identical except
that `features` names the fp32 file; its version is unchanged, since its classes are the same.
fp32 features match fp16 to cosine 0.9997, so CPU numbers differ from the rig's in the third
decimal: use it for development, never for evaluation.

Standard library only. Rerun it whenever manifest.toml changes, and commit both files; the
twins are model files like the others (published with ml/models/publish.py).
"""

from __future__ import annotations

import hashlib
import json
import re
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "manifest.toml"
TARGET = HERE / "manifest.cpu.toml"
FILES = HERE / "files"
HEAD_FORMAT = "pdm-linear-head/1"
HEADS = ("disease_head", "species_head", "plant_probe")   # the entries holding a pdm-linear-head/1 file


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def fp32_name(fp16: str) -> str:
    return re.sub(r"-fp16\.onnx$", "-fp32.onnx", fp16)


def head_twin(file: str, bioclip_fp32_sha: str) -> str:
    """Write the CPU twin of a head file and return its path."""
    path = FILES / file
    if not path.exists():
        raise SystemExit(f"{path} is missing: fetch it first (docs/vision/README.md §6)")
    doc = json.loads(path.read_text())
    if doc.get("format") != HEAD_FORMAT:
        raise SystemExit(f"{path} is not a {HEAD_FORMAT} file")
    prefix = doc["features"].split("+", 1)[0]
    doc["features"] = f"{prefix}+{bioclip_fp32_sha[:16]}"
    twin = re.sub(r"\.json$", ".cpu.json", file)
    (FILES / twin).write_text(json.dumps(doc, indent=1) + "\n")   # as ml/pdm_vision/headfile.py writes
    return twin


def main() -> None:
    text = SOURCE.read_text()
    entries = tomllib.loads(text)["model"]
    bioclip = next(e for e in entries if e["name"] == "bioclip")
    bioclip_fp32 = FILES / fp32_name(bioclip["file"])
    if not bioclip_fp32.exists():
        raise SystemExit(f"{bioclip_fp32} is missing: fetch it first (docs/vision/README.md §6)")
    bioclip_fp32_sha = sha256(bioclip_fp32)

    lines = text.splitlines()
    out = [
        "# GENERATED by `python -m ml.models.cpu_manifest` from manifest.toml: don't edit.",
        "# The fp32 exports and the heads' CPU twins, for ORT_EP=cpu on a development machine",
        "# (docs/vision/dev-roadmap.md, task M9).",
        "#",
    ]
    swapped = twins = 0
    name = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        if n := re.match(r'^name\s*=\s*"(.+)"', line):
            name = n[1]
        m = re.match(r'^(file\s*=\s*")(.+)(".*)$', line)
        if m:
            new = None
            if m[2].endswith("-fp16.onnx"):
                new = fp32_name(m[2])
                swapped += 1
            elif name.startswith(HEADS):
                new = head_twin(m[2], bioclip_fp32_sha)
                twins += 1
            if new is not None:
                path = FILES / new
                if not path.exists():
                    raise SystemExit(f"{path} is missing: export it, or fetch it (docs/vision/README.md §6)")
                nxt = lines[i + 1]
                if not nxt.startswith("sha256"):
                    raise SystemExit(f"expected sha256 after {line!r}")
                out.append(f"{m[1]}{new}{m[3]}")
                out.append(re.sub(r'"[0-9a-f]{64}"', f'"{sha256(path)}"', nxt))
                i += 2
                continue
        if re.match(r'^precision\s*=\s*"fp16"', line):
            out.append(re.sub(r'"fp16".*$', '"fp32"', line))
        else:
            out.append(line)
        i += 1
    TARGET.write_text("\n".join(out) + "\n")
    print(f"{TARGET.name}: {swapped} files swapped to fp32, {twins} head twins")


if __name__ == "__main__":
    main()
