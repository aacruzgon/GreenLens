// Generates src/api/generated/schema.ts from the backend's committed spec (docs/frontend 9).
// A $ref to a schema missing from components is replaced with a plain string and reported,
// so a spec bug shows up as a warning here instead of blocking the app's types.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const specPath = path.resolve(here, "../../backend/openapi.json");
const outPath = path.resolve(here, "../src/api/generated/schema.ts");

const spec = JSON.parse(fs.readFileSync(specPath, "utf8"));
const schemas = spec.components?.schemas ?? {};
const missing = new Set();

function patch(node) {
  if (Array.isArray(node)) return node.forEach(patch);
  if (!node || typeof node !== "object") return;
  for (const [key, value] of Object.entries(node)) {
    if (value && typeof value === "object" && typeof value.$ref === "string") {
      const name = value.$ref.replace("#/components/schemas/", "");
      if (value.$ref.startsWith("#/components/schemas/") && !(name in schemas)) {
        missing.add(name);
        node[key] = { type: "string", description: `Missing from the spec: ${name}` };
        continue;
      }
    }
    patch(value);
  }
}
patch(spec);

// utoipa emits description-only members inside allOf ({ type: "object", description }), which
// openapi-typescript renders as Record<string, never> and so makes the whole type unbuildable. Drop them.
const shapeKeys = ["properties", "additionalProperties", "allOf", "oneOf", "anyOf", "$ref", "enum", "items"];
function dropEmptyAllOf(node) {
  if (Array.isArray(node)) return node.forEach(dropEmptyAllOf);
  if (!node || typeof node !== "object") return;
  if (Array.isArray(node.allOf)) {
    node.allOf = node.allOf.filter((m) => !(m && m.type === "object" && !shapeKeys.some((k) => k in m)));
  }
  Object.values(node).forEach(dropEmptyAllOf);
}
dropEmptyAllOf(spec);

for (const name of missing) {
  console.warn(`gen:api: backend/openapi.json references #/components/schemas/${name}, which it doesn't define`);
}

const ast = await openapiTS(spec);
const header = "// Generated by scripts/gen-api.mjs from backend/openapi.json. Never edit by hand.\n\n";
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header + astToString(ast));
console.log(`gen:api: wrote ${path.relative(process.cwd(), outPath)}`);
