//! Embeds every `backend/migrations/*.surql` file but the schema as `MIGRATIONS`, sorted:
//! the numbered files in number order, then `knowledge.surql` ([database 1], applying the
//! migrations). A bad name or a duplicate number fails the build, so the binary and its
//! migrations can't drift and a new file needs no code change.
//!
//! [database 1]: https://github.com/aacruzgon/GreenLens/blob/main/docs/database/README.md#1-version-and-setup
//! (Clippy's `print_stdout` skips build scripts, which talk to cargo on standard output.)

use std::{collections::BTreeMap, env, fmt::Write as _, fs, path::PathBuf};

#[path = "src/migrate/naming.rs"]
mod naming;

use naming::FileKind;

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let dir = manifest.join("../../migrations");
    // A directory: cargo re-runs the script when any file in it changes, appears or goes.
    println!("cargo::rerun-if-changed={}", dir.display());

    let mut numbered: BTreeMap<u16, (String, PathBuf)> = BTreeMap::new();
    let mut knowledge = None;
    // No directory: a dependency-only build (cargo-chef's `cook`) with stand-in sources. A real
    // build can't get here, since `client.rs` embeds `migrations/schema.surql`.
    let entries = fs::read_dir(&dir)
        .into_iter()
        .flatten()
        .map(|entry| entry.expect("a readable directory entry").path());
    for path in entries {
        if path.extension().is_none_or(|ext| ext != "surql") {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_else(|| panic!("{}: a migration name is UTF-8", path.display()))
            .to_owned();
        let path = path
            .canonicalize()
            .unwrap_or_else(|e| panic!("{name}: {e}"));
        match naming::file_kind(&name) {
            Ok(FileKind::Schema) => {}
            Ok(FileKind::Knowledge) => knowledge = Some((name, path)),
            Ok(FileKind::Versioned(number)) => {
                if let Some((other, _)) = numbered.insert(number, (name.clone(), path)) {
                    panic!(
                        "{name} and {other} share the number {number:04}: give one the next number"
                    );
                }
            }
            Err(refused) => panic!("{refused}"),
        }
    }

    let mut out = String::from(
        "/// Generated by `build.rs`: every migration file but the schema, in order.\n",
    );
    out.push_str("pub const MIGRATIONS: &[Migration] = &[\n");
    for (name, path) in numbered.values().chain(knowledge.as_ref()) {
        let path = path.to_str().expect("a UTF-8 path");
        writeln!(
            out,
            "    Migration {{ name: {name:?}, sql: include_str!({path:?}) }},"
        )
        .expect("writing to a String");
    }
    out.push_str("];\n");
    let target =
        PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets it")).join("migrations.rs");
    fs::write(&target, out).unwrap_or_else(|e| panic!("write {}: {e}", target.display()));
}
