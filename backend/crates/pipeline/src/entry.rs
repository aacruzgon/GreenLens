#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn segmentation_first_only_for_measurable_unanswered_indicators() {
        let ind: IndicatorSeed = serde_json::from_value(serde_json::json!({
            "id": "tomato_septoria_leaf_spot.small_spots", "text": "Spots about 1.5-3 mm across",
            "question": "Are the spots small?", "weight": 3, "discriminating": true,
            "where": "lower_leaves", "image_kinds": ["leaf_closeup"],
            "measure": {"quantity": "lesion_diameter_mm", "stat": "median", "min": 1.5, "max": 3}
        }))
        .unwrap();
        let none = AnswerSet::default();
        assert!(needs_segmentation(
            ImageKind::LeafCloseup,
            true,
            &[&ind],
            &none
        ));
        assert!(
            !needs_segmentation(ImageKind::LeafCloseup, false, &[&ind], &none),
            "no depth"
        );
        assert!(
            !needs_segmentation(ImageKind::WholePlant, true, &[&ind], &none),
            "kind can't show it"
        );
        let measured = [IndicatorEvidence {
            indicator_id: ind.id.clone(),
            text: String::new(),
            weight: ind.weight,
            answer: domain::scan::Answer::Yes,
            reason: String::new(),
            source: EvidenceSource::Measurement,
            measured: None,
        }];
        assert!(!needs_segmentation(
            ImageKind::LeafCloseup,
            true,
            &[&ind],
            &AnswerSet::new(&measured)
        ));
    }
}
