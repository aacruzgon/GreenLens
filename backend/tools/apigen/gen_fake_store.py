#!/usr/bin/env python3
"""Generate api's test composite store: one struct holding a mockall mock per store trait,
implementing every trait method by delegation, default-bodied methods included, so a test sets
expectations for every method. Regenerate when a store trait changes.

usage (from backend/): python3 tools/apigen/gen_fake_store.py \
    crates/domain/src/ports/store bins/api/src/tests/fake_store.rs && cargo fmt -p api
"""
import re, sys
from pathlib import Path

SRC = Path(sys.argv[1])  # crates/domain/src/ports/store
OUT = Path(sys.argv[2])

def strip_comments(text):
    return '\n'.join(l for l in text.split('\n') if not l.strip().startswith('//'))

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def signatures(body):
    """Every `async fn` signature in a trait body, bodiless (`...;`) or with a default body
    (`... { ... }`): the text after `async fn` up to the `;` or the opening brace at depth 0,
    with any default body skipped by brace matching. `->` is not an angle bracket."""
    out, i = [], 0
    while True:
        i = body.find('async fn ', i)
        if i < 0:
            return out
        j = i + len('async fn ')
        depth, k = 0, j
        while k < len(body):
            ch = body[k]
            if body.startswith('->', k):
                k += 2
                continue
            if ch in '(<[':
                depth += 1
            elif ch in ')>]':
                depth -= 1
            elif depth == 0 and ch in ';{':
                break
            k += 1
        out.append(body[j:k].strip())
        if k < len(body) and body[k] == '{':
            braces = 0
            while k < len(body):
                if body[k] == '{':
                    braces += 1
                elif body[k] == '}':
                    braces -= 1
                    if braces == 0:
                        break
                k += 1
        i = k + 1

mods = []
fields = []
for f in sorted(SRC.glob('*.rs')):
    text = strip_comments(f.read_text())
    text = text.split('#[cfg(test)]')[0]
    uses = re.findall(r'^use [\s\S]*?;\n', text, re.M)
    for m in re.finditer(r'pub trait (\w+): Send \+ Sync \{([\s\S]*?)\n\}', text):
        trait, body = m.group(1), m.group(2)
        methods = signatures(body)
        impls = []
        for sig in methods:
            name = re.match(r'(\w+)', sig).group(1)
            params = sig[sig.index('(')+1: sig.rindex(')', 0, sig.index('->') if '->' in sig else len(sig))]
            # parameter names after &self
            parts, depth, cur = [], 0, ''
            for ch in params:
                if ch in '(<[': depth += 1
                if ch in ')>]': depth -= 1
                if ch == ',' and depth == 0:
                    parts.append(cur); cur = ''
                else:
                    cur += ch
            parts.append(cur)
            args = [p.split(':')[0].strip() for p in parts if p.strip() and p.strip() != '&self']
            sig = sig.replace('crate::', 'domain::')
            impls.append(f"    async fn {sig.strip()} {{\n        self.{snake(trait)}.{name}({', '.join(args)}).await\n    }}")
        field = snake(trait)
        fields.append((field, trait))
        use_block = ''.join(u.replace('crate::', 'domain::') for u in uses)
        use_block = use_block.replace('use domain::{', 'use domain::{', 1)
        mods.append(f"mod {field} {{\n    #![allow(unused_imports, reason = \"copied from the trait's module\")]\n    {use_block.replace(chr(10), chr(10)+'    ')}\n    use domain::ports::*;\n\n    #[async_trait::async_trait]\n    impl {trait} for super::FakeStore {{\n" + '\n'.join('    '+l for l in '\n'.join(impls).split('\n')) + "\n    }\n}\n")

out = ['//! Generated by `backend/tools/apigen/gen_fake_store.py` from `domain::ports::store`: a `Store` made of one',
       '//! mockall mock per repository trait, each trait implemented by delegation. Tests set',
       '//! expectations on the field for the area they exercise.',
       '',
       '#![allow(clippy::pedantic, reason = "generated")]',
       '',
       'use domain::ports::{' + ', '.join(f'Mock{t}' for _, t in fields) + '};',
       '',
       '/// Every store trait, mocked.',
       '#[derive(Default)]',
       'pub struct FakeStore {']
for field, trait in fields:
    out.append(f'    pub {field}: Mock{trait},')
out.append('}')
out.append('')
out.extend(mods)
OUT.write_text('\n'.join(out))
print(len(fields), 'traits')
